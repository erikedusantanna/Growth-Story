CHARS = {}  # char -> list of CELL_H strings of CELL_W chars ('#'/'.')

def blank_cell():
    return ["." * CELL_W for _ in range(CELL_H)]

for ch, rows in BASE.items():
    if ch in ("c_", "C_"):
        continue
    cell = ["." * GW, "." * GW] + rows
    CHARS[ch] = cell
CHARS["ç"] = ["." * GW, "." * GW] + BASE["c_"]
CHARS["Ç"] = ["." * GW, "." * GW] + BASE["C_"]

for ch, (base_ch, acc) in ACCENTED.items():
    top = ACCENTS[acc]
    cell = [top[0], top[1]] + BASE[base_ch]
    CHARS[ch] = cell

ORDER = list(CHARS.keys())

# --- Empacota no atlas -----------------------------------------------------------
COLS = 12
ROWS = (len(ORDER) + COLS - 1) // COLS
ATLAS_W = COLS * (CELL_W + GAP) + GAP
ATLAS_H = ROWS * (CELL_H + GAP) + GAP

canvas = [[(0, 0, 0, 0)] * ATLAS_W for _ in range(ATLAS_H)]
positions = {}

for idx, ch in enumerate(ORDER):
    col = idx % COLS
    row = idx // COLS
    ox = GAP + col * (CELL_W + GAP)
    oy = GAP + row * (CELL_H + GAP)
    positions[ch] = (ox, oy)
    cell = CHARS[ch]
    for y, line in enumerate(cell):
        for x, c in enumerate(line):
            if c == "#":
                canvas[oy + y][ox + x] = (255, 255, 255, 255)


def write_png(path, c):
    h = len(c)
    w = len(c[0])
    raw = bytearray()
    for row in c:
        raw.append(0)
        for px in row:
            raw.extend(px)

    def chunk(tag, data):
        body = struct.pack(">I", len(data)) + tag + data
        return body + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b"")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(png)
    print("ok", os.path.relpath(path, ROOT), f"{w}x{h}")


write_png(OUT_PNG, canvas)

